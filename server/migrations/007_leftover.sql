-- M1-10 留量（总纲 §2.6、§3 决议 4；ADR-0007）
--
-- 002 的注释里说好了：「留量『吃剩的』引用与上浮（#22）先只留字段/占位」。本票如约落值，
-- **表形状按 002 预留的来，不另造一套**：
--
--   * `meal_events.leftover_menu_slot_id` —— 「吃剩的」引用（引用哪一餐）。落在这张
--     append-only 事件表上而不是新开一张「留量表」：引用关系是**菜单变化的一部分**
--     （预定一餐为「吃剩的」就是一条 decide/replace 事件），ADR-0007 说历史只在事件流里。
--     取消被引用的那一餐时，引用方也**追加一条取消事件**（见 domain/slots.ts 的 cancelSlot），
--     而不是去改什么状态——append-only 没有可改的状态表。
--
--   * `meal_event_dishes.keep_leftover` —— 单道菜「多做留到下顿」的标记（002 已落列）。
--     上浮生效条件 = 这个标记 **∧** 存在有效引用（总纲 §2.6），判定写领域层。
--
-- 本票新增的只有两块：
--
-- 1. **家规表（单例配置，总纲 §3：「家规 = 一份可调的单例配置，全部可调」）**。
--    本票只放自己需要的那个值：**留量上浮系数**（默认 1.5×）。单行表 + `CHECK (id = 1)`，
--    SQLite 没有「单例」类型，就用主键把「只有一份」钉死（与 #20 的 006 同一路数）。
--
--    ⚠️ 集成注记：本表与 #20（M1-08）并行实施中的 `family_rules`（冷藏期天数 + 餐次截止时刻）
--    是**同名同职责的两份实现**——两条分支各自都基于 01b6766、谁也看不见谁，因此都建了
--    「家规单例表」。合入 main 时由调度层合并成**一张表**（列求并集，仍是 id=1 单行）。
--    读取口同样会合并：本票的 `server/src/domain/family-rules.ts` 只读 `leftover_uplift`，
--    #20 的只读 `cool_off_days` / `lunch_cutoff_hour` / `dinner_cutoff_hour`，合并时并成一个文件。
--
-- 2. **引用查询的索引**：`meal_events.leftover_menu_slot_id`（002 只落了列没建索引）。
--    「谁引用了这一餐」是取消联动与上浮判定的热查询，给它一条索引。

-- ---------------------------------------------------------------- 家规（单例配置）

-- 集成（006 与 007 并表）：006（#20）已经建好 family_rules 单例表并种下 id=1 那行
-- （冷藏期天数 + 餐次截止时刻）。这里**不再建表**，只给那张表补本票要的列——
-- 家规是同一份配置，两张同名表只会让「家规读在哪」分叉。
-- ALTER 必须带 DEFAULT：SQLite 不许给非空列加 CHECK 却没有默认值；而单例行已存在，
-- DEFAULT 正好把这一项回填到既有那行上，语义就是「给现有家规补上留量上浮系数」。
ALTER TABLE family_rules ADD COLUMN leftover_uplift REAL NOT NULL DEFAULT 1.5
  CHECK (leftover_uplift BETWEEN 1 AND 5);
UPDATE family_rules SET leftover_uplift = 1.5 WHERE id = 1;

-- ---------------------------------------------------------------- 「吃剩的」引用索引

-- 「谁引用了这一餐」：取消联动（找引用方追加取消事件）与上浮判定（有效引用是否存在）
-- 都按这一列查，002 只落了列没建索引。
CREATE INDEX idx_meal_events_leftover ON meal_events (leftover_menu_slot_id);
