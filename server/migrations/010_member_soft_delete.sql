-- 家人可删（本票）：**软删除**，不是删行。
--
-- 为什么是软删除而不是 `DELETE FROM members`：
--   * `dish_feedback.member_id` 是 `ON DELETE CASCADE`（006）——硬删会把「这个人点过的踩/赞」
--     一起带走，而反馈是近 30 天摘要与冷藏期的输入，也正是「历史积累喜好」这条产品闭环的一半。
--     历史反馈的价值在于「那道菜确实被这一家人否决过」，不是「这个人还在不在名单上」。
--   * `meal_event_diners` 存的是姓名/头像**快照**（002 的注释：家人后来改名/删号也不改写历史），
--     所以留痕本来就不受影响；软删除把这个原则贯彻到画像与反馈上。
--   * 删除的真实语义是「从此不再参与」——不进用餐者名单、忌口/爱吃不再生效——而不是
--     「过去没发生过」。一条时间戳就能准确表达它，且将来若要「恢复」也不必重建画像。
--
-- 标记列选 `deleted_at TEXT`（NULL = 在用）而不是 `active INTEGER`：时间戳顺带回答「什么时候删的」，
-- 而布尔列永远要多问一句「那是什么时候」（真删掉的人连这一问都答不了）。NULL 作为「在用」是 SQL 的
-- 常态写法，读取侧一律写 `deleted_at IS NULL`，不需要额外的默认值约定。
--
-- ⚠️ SQLite 的 `ALTER TABLE ADD COLUMN` 限制：不能加「非空且无默认值」的列。`deleted_at` 可空，
-- 天然满足；且**不改** 001 已有的 `CHECK (kind <> 'child' OR birth_month IS NOT NULL)`——
-- 迁移历史是 append-only 的（见本目录 README），那条约束继续管着「小孩必有出生年月」。
ALTER TABLE members ADD COLUMN deleted_at TEXT;

-- 不建索引：家人是**个位数行**的家庭小表（种子里 4 行），全表扫比走索引更便宜；
-- 索引留给餐槽事件、反馈、菜谱这些会长的表。
--
-- 名字（`name`）刻意**不加 UNIQUE**：真实家庭会重名（两个「姥姥」、孩子的小名撞车），
-- 而「列表里两个妈妈很怪」这件事应该由编辑流程解决（改名），不该由数据库把
-- 一个合法输入变成错误——何况家族里同名是常态，不是脏数据。
-- 身份由 `id` 承担（主键，永唯一）；界面一律靠 `id` 区分卡片与操作入口，不靠名字。
