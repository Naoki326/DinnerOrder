-- 菜谱来源链接（「贴链接/贴文字导入」票）：给 `recipes` 加一列**原始来源**。
--
-- 为什么是**新列**而不是把 `source` 的 CHECK 放宽：
--   * `source` 记录的是「这道菜从哪来」的**封闭四值**（口述/HowToCook/爬取/LLM 生成，002 的 CHECK），
--     `howtocook` / `scraped` 那两值在**转正门槛**的读法里是有意义的（ADR-0006 判的是外部数据）。
--     为「小红书链接」加第五个值就要重建 `recipes` 表放宽 CHECK，而 SQLite 在 `foreign_keys=ON`
--     下 DROP 父表会被 `meal_event_dishes` / `recipe_ingredients` 等子表挡住，`db.transaction()`
--     内关 FK 又是无效的（事务内 PRAGMA 被忽略，实测）。重建这条路走不通，而它本来也不必要。
--   * 更重要的：`source` 回答的是「**信任档**」（这一行是家里确认过的，还是外部素材），
--     而链接回答的是「**出处**」——两件不同的事。挤进同一个封闭枚举会让将来每加一个来源
--     都要改门槛判定。
--
-- 本列只给「贴链接/贴文字导入」落库的菜写；手写录入、导入工具、种子行都是 NULL
-- （它们没有可回填的单一链接，硬编一个就是编数据）。NULL = 没有记录来源，不是「来源未知」的另一种状态。
--
-- 不加索引：它只作展示与回溯（编辑器上显示一句「来源：<链接>」），不参与任何查询或过滤。
ALTER TABLE recipes ADD COLUMN source_ref TEXT;
