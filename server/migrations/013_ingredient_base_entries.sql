-- 食材字典补录「扁平 + 三件套」（issue #28）
--
-- 决策来源：2026-09-20 grilling 会话；254 条归一失败的四分类（44 杂讯 / 错别字 / 粒度断层 /
-- 真缺长尾）与方案全文见 `docs/research/2026-09-20-external-pool-observation.md` §7 与
-- `docs/agents/open-items.md` 的「下轮工单 2」。
--
-- 三件套（本文件是它们的落地）：
--
--   1. **裸名基础条目**：菜谱写「猪肉」「鸡肉」「芝麻」「米饭」这类**粗粒度语言**时，字典里有处落。
--      基础条目的语义 = **无部位/形态要求**（店里随意买哪种都行）。它与既有的细粒度条目
--      （猪排骨、白芝麻）**并存**，两者在买菜清单上**分列不合**——细粒度条目的部位硬要求
--      必须看得见（「做糖醋排骨买回梅花肉就废了」），合并会丢掉这条信息。
--
--   2. **「含」指针连部位**：细粒度条目 → 基础条目（猪排骨含猪肉、白芝麻含芝麻）。
--      忌口沿**既有**展开机制自动向上传播（`ingredient_contains` 是 002 建的表，
--      `domain/ingredients.ts` 的 `expandContains` 做递归展开，菜谱忌口推导与推荐期硬过滤
--      都读展开后的并集）——**零新机制**，推荐与换菜两处过滤自动生效。
--      方向单向：只有「忌基础类 → 连细类一起排」，不存在反向。
--
--   3. **品种子类不入库**：黑猪/普通猪这类**品种**信息无需系统追踪（买菜随意买）。
--      因此本文件**不建 parent_id 层级**、也不为品种加条目。被否决的层级模型与理由见上面那份
--      研究文档：部位与品种是两个维度（品种可随意替换、部位不可），层级化后「忌子类不忌基础类」
--      的语义分叉必须回答，而本家忌口都是基础类级别；267 项既有条目重分层也没有权威来源。
--      **将来若真要按品种追踪，须另立 ADR**（这是本票记下的、刻意留下的口子）。
--
-- 头部范围：**只补导入报告里高频出现的家常项**（约 10–20 条），**长尾真缺项不补**
-- （印度综合香料粉、白芷、酥油、欧芹…——不为家里不做的菜系扩字典，见 issue 的 Out of Scope）。
-- 报告里那批长尾仍然会出现在 `unmatched` 清单里，那是**刻意留着的可见欠账**：
-- 等观察轮有菜真上桌缺料再按需补（研究文档 §7 的原话）。
--
-- 时令月份：**本轮新增条目全部是「四季常售」**，所以本文件**不写月份**——这是刻意做的
-- 显式判断，不是漏录（issue story 10 的「新增条目带时令月份」由下面这条口径兑现）：
--
--   * 002/005 起，这份手工表的**实际收录范围是「当季的菜」（蔬菜/菌菇）**：现有 40 种全部是
--     蔬菜与菌菇，肉禽/主粮/调料一个都没录（大米/面粉/猪肉/牛肉都没有月份）。新增的
--     猪肉/鸡肉/芝麻/米饭/蒜粉/姜粉/椒盐粉/白葡萄酒/芥末/小苏打也属于这一类——
--     肉店与超市全年都有，录一个「当季月份」反而是假信号。
--   * 按 002 起就有的口径**不录月份 = 四季有售**（见 005 文件头：给每个食材填满 12 个月
--     等于把时令信号抹成常量，推荐排序的时令位就永远是同一个分）。所以「每条都做了时令判断」
--     的落地就是：**新增的 10 条全是四季常售，一条也不进时令表**（时令表仍是 40 种）。
--     同理，把「羊排」「南乳」这类**部位/品种**的当季性录上去也会把肉类带进一张只收蔬菜的表——
--     那不是本票的活。
--
-- 被否决的备选：给「羊排」建一条带秋冬月份的新条目（试过，会让时令表变成 41 种，越过
-- spec §5 的「30–40 种」硬边界，且把肉类混进一张只收蔬菜的表）。现在羊排走
-- `lamb` 的别名（同一种肉的部位叫法，字典的粒度到「羊肉」为止）。
--
-- 「新增条目必须连带『含』指针」的例外（**刻意留下的空，不是漏挂**）：
--   * `white_wine`（白葡萄酒）与 `baking_soda`（小苏打）**没有可挂的基础类**——酒类在字典里
--     没有基础条目（料酒/白酒/啤酒/白葡萄酒各自成一类，强行挂一个等于把忌口语义挂错），
--     膨松剂同理（发粉是泡打粉，与小苏打不是同一样东西）。宁可留空，也不编一条假关系。
--   * `pork` / `chicken` / `sesame` / `cooked_rice` / `mustard` 是**指针的靶子**而不是源：
--     它们是基础类，按单向原则只被指、不指人。例如 `yellow_mustard`（黄芥末）指向 `mustard`，
--     而 `青芥末`/`芥末油` 靠**包含匹配**归到 `mustard`（名字里含「芥末」且候选唯一）——
--     这一层不需要额外指针。

